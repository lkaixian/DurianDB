// Browser check for the mimic shape editor in the dashboard designer. Same setup as browser_forms.mjs. Expect no problems.
import fs from "node:fs";
const out = process.argv[2]; fs.mkdirSync(out, {recursive: true});
const targets = await (await fetch("http://127.0.0.1:9222/json/list")).json();
const ws = new WebSocket(targets.find(t => t.type === "page").webSocketDebuggerUrl);
await new Promise(r => ws.addEventListener("open", r));
let id = 0; const pend = new Map(); const problems = [];
ws.addEventListener("message", e => { const m = JSON.parse(e.data);
  if (m.id && pend.has(m.id)) { pend.get(m.id)(m.result ?? m.error); pend.delete(m.id); }
  if (m.method === "Runtime.exceptionThrown") problems.push("EXC " + m.params.exceptionDetails.text + " " + (m.params.exceptionDetails.exception?.description ?? ""));
  if (m.method === "Runtime.consoleAPICalled" && m.params.type === "error") problems.push("CONSOLE " + m.params.args.map(a => a.value ?? a.description).join(" ")); });
const send = (method, params = {}) => new Promise(r => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify({id: i, method, params})); });
const ev = async expr => (await send("Runtime.evaluate", {expression: expr, returnByValue: true, awaitPromise: true})).result?.value;
const sleep = ms => new Promise(r => setTimeout(r, ms));
const shot = async n => fs.writeFileSync(`${out}/${n}.png`, Buffer.from((await send("Page.captureScreenshot", {format: "png"})).data, "base64"));
const go = async h => { await ev(`location.hash=${JSON.stringify(h)}`); await sleep(1800); };
await send("Page.enable"); await send("Runtime.enable");
await send("Network.enable"); await send("Network.setCacheDisabled", {cacheDisabled: true}); await send("Page.navigate", {url: (process.env.DURIAN_BASE ?? "http://127.0.0.1:8766") + "/"}); await sleep(2000);
await ev(`(()=>{const f=document.querySelector('#login');f.username.value='admin';f.password.value=${JSON.stringify(process.env.DURIAN_ADMIN_PASSWORD)};f.requestSubmit()})()`); await sleep(2500);
await go("#design/_new");
await ev(`(()=>{const f=document.querySelector('#df');f.name.value='mm-test';f.title.value='Mimic test'})()`);
await ev(`document.querySelector('[data-add=mimic]').click()`); await sleep(800);
const info = () => ev(`JSON.stringify({rows:document.querySelectorAll('.mm-ed [data-k]').length, json:JSON.parse(document.querySelector('[data-f=rest]').value).shapes.length, svgShapes:document.querySelectorAll('#pv svg.mimic > *').length})`);
console.log("start:", await info());
const first = () => ev(`(()=>{const r=document.querySelector('.mm-ed [data-k="0"]');return r.querySelector('[data-mf=x]').value})()`);
const x0 = await first();
await ev(`document.querySelector('.mm-ed [data-k="0"] [data-mm=r]').click()`); await sleep(500);
console.log("nudge right:", x0, "->", await first());
await ev(`(()=>{const i=document.querySelector('.mm-ed [data-k="0"] [data-mf=label]');i.value='Boiler';i.dispatchEvent(new Event('change',{bubbles:true}))})()`); await sleep(500);
console.log("label in json:", await ev(`JSON.parse(document.querySelector('[data-f=rest]').value).shapes[0].label`));
await ev(`(()=>{document.querySelector('.mm-ed [data-ms]').value='circle';document.querySelector('.mm-ed [data-mm=add]').click()})()`); await sleep(500);
console.log("after add:", await info());
await ev(`document.querySelector('.mm-ed [data-k="1"] [data-mm=x]').click()`); await sleep(500);
console.log("after remove:", await info());
await ev(`document.querySelector('#sv').click()`); await sleep(1500);
console.log("save:", await ev(`document.querySelector('#dm').innerText`));
await shot("mimic-editor");
console.log("unlabelled:", await ev(`[...document.querySelectorAll('.mm-ed input,.mm-ed select')].filter(e=>!e.closest('label')).length`));
console.log("problems:", JSON.stringify(problems));
process.exit(problems.length ? 1 : 0);
